@Composable
private fun QRInscripcionSuccessSection(
    qrData: QRInscripcionResponse,
    isDownloading: Boolean,
    onDescargar: () -> Unit
) {
    // Procesar imagen QR fuera del composable
    val qrBitmap = remember(qrData.qr.qr_image) {
        try {
            val base64String = qrData.qr.qr_image.substringAfter("base64,")
            val decodedBytes = Base64.decode(base64String, Base64.DEFAULT)
            BitmapFactory.decodeByteArray(decodedBytes, 0, decodedBytes.size)
        } catch (e: Exception) {
            null
        }
    }

    Column {
        // QR Code
        Card(
            modifier = Modifier.fillMaxWidth(),
            shape = RoundedCornerShape(12.dp),
            colors = CardDefaults.cardColors(containerColor = Color.White),
            elevation = CardDefaults.cardElevation(defaultElevation = 4.dp)
        ) {
            Column(
                modifier = Modifier.padding(24.dp),
                horizontalAlignment = Alignment.CenterHorizontally
            ) {
                Text(
                    text = "QR de Inscripción Generado",
                    fontSize = 18.sp,
                    fontWeight = FontWeight.Bold,
                    color = Color(0xFF1E3A8A)
                )

                Spacer(modifier = Modifier.height(16.dp))

                // Mostrar imagen QR
                if (qrBitmap != null) {
                    Image(
                        bitmap = qrBitmap.asImageBitmap(),
                        contentDescription = "Código QR de Inscripción",
                        modifier = Modifier.size(250.dp)
                    )
                } else {
                    Box(
                        modifier = Modifier
                            .size(250.dp)
                            .background(Color.Gray.copy(alpha = 0.1f)),
                        contentAlignment = Alignment.Center
                    ) {
                        Text(
                            text = "Error al cargar QR",
                            color = Color.Gray
                        )
                    }
                }

                Spacer(modifier = Modifier.height(16.dp))

                // Información de expiración
                Text(
                    text = "Válido hasta:",
                    fontSize = 12.sp,
                    color = Color.Gray
                )
                Text(
                    text = formatearFechaExpiracion(qrData.qr.expires_at),
                    fontSize = 14.sp,
                    fontWeight = FontWeight.Medium,
                    color = Color(0xFFDC2626)
                )

                Spacer(modifier = Modifier.height(8.dp))

                // Tipo de QR
                Box(
                    modifier = Modifier
                        .background(
                            Color(0xFF4CAF50).copy(alpha = 0.1f),
                            RoundedCornerShape(12.dp)
                        )
                        .padding(horizontal = 12.dp, vertical = 6.dp)
                ) {
                    Text(
                        text = "QR de Inscripción",
                        fontSize = 12.sp,
                        color = Color(0xFF4CAF50),
                        fontWeight = FontWeight.Bold
                    )
                }
            }
        }

        Spacer(modifier = Modifier.height(16.dp))

        // Botón descargar
        Button(
            onClick = onDescargar,
            modifier = Modifier.fillMaxWidth(),
            colors = ButtonDefaults.buttonColors(
                containerColor = Color(0xFF4CAF50)
            ),
            shape = RoundedCornerShape(12.dp),
            enabled = !isDownloading
        ) {
            if (isDownloading) {
                CircularProgressIndicator(
                    modifier = Modifier.size(16.dp),
                    color = Color.White,
                    strokeWidth = 2.dp
                )
                Spacer(modifier = Modifier.width(8.dp))
                Text("Descargando...")
            } else {
                Icon(
                    imageVector = Icons.Default.Download,
                    contentDescription = "Descargar"
                )
                Spacer(modifier = Modifier.width(8.dp))
                Text("Descargar QR")
            }
        }

        Spacer(modifier = Modifier.height(8.dp))

        // Información adicional
        Card(
            modifier = Modifier.fillMaxWidth(),
            shape = RoundedCornerShape(8.dp),
            colors = CardDefaults.cardColors(containerColor = Color(0xFFF0F8FF))
        ) {
            Column(
                modifier = Modifier.padding(12.dp)
            ) {
                Text(
                    text = "ℹ️ Instrucciones:",
                    fontSize = 14.sp,
                    fontWeight = FontWeight.Bold,
                    color = Color(0xFF1E3A8A)
                )
                Spacer(modifier = Modifier.height(4.dp))
                Text(
                    text = "• Comparte este QR con tus estudiantes\n• Los estudiantes escanean el QR para auto-inscribirse\n• El código es válido por 30 días\n• Solo funciona para esta materia específica",
                    fontSize = 12.sp,
                    color = Color.Gray
                )
            }
        }
    }
}

// Función para formatear la fecha de expiración
private fun formatearFechaExpiracion(expiresAt: String): String {
    return try {
        val inputFormat = SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss.SSS'Z'", Locale.getDefault())
        val outputFormat = SimpleDateFormat("dd/MM/yyyy HH:mm", Locale.getDefault())
        val date = inputFormat.parse(expiresAt)
        outputFormat.format(date ?: Date())
    } catch (e: Exception) {
        expiresAt
    }
}