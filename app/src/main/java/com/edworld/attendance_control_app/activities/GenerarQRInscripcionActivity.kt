class GenerarQRInscripcionActivity : ComponentActivity() {

    // Estados para la UI
    private var isLoading by mutableStateOf(false)
    private var isDownloading by mutableStateOf(false)
    private var qrGenerated by mutableStateOf<QRInscripcionResponse?>(null)
    private var errorMessage by mutableStateOf("")

    // Datos recibidos del Intent
    private var materiaId by mutableStateOf(0)

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        // Obtener datos del Intent
        materiaId = intent.getIntExtra("materia_id", 0)

        setContent {
            GenerarQRInscripcionScreen(
                qrGenerated = qrGenerated,
                isLoading = isLoading,
                isDownloading = isDownloading,
                errorMessage = errorMessage,
                onNavigateBack = { finish() },
                onGenerarQR = { generarQRInscripcion() },
                onDescargarQR = { descargarQR() }
            )
        }

        // Generar QR automáticamente al abrir la activity
        generarQRInscripcion()
    }

    private fun generarQRInscripcion() {
        isLoading = true
        errorMessage = ""
        qrGenerated = null

        lifecycleScope.launch {
            try {
                val userId = getUserId()
                if (userId == null) {
                    errorMessage = "Error: No se encontró ID del usuario"
                    isLoading = false
                    return@launch
                }

                val request = GenerarQRInscripcionRequest(
                    materia_id = materiaId,
                    docente_id = userId.toInt(),
                    duracion_dias = 30
                )

                val response = ApiClient.client.post("${Constants.BASE_URL}/academic/materia/qr/inscripcion") {
                    contentType(ContentType.Application.Json)
                    setBody(request)
                }

                when (response.status) {
                    HttpStatusCode.OK -> {
                        val qrResponse: QRInscripcionResponse = response.body()
                        qrGenerated = qrResponse
                        isLoading = false
                        Toast.makeText(
                            this@GenerarQRInscripcionActivity,
                            "QR de inscripción generado exitosamente",
                            Toast.LENGTH_SHORT
                        ).show()
                    }

                    HttpStatusCode.NotFound -> {
                        val errorResponse = response.body<Map<String, String>>()
                        errorMessage = errorResponse["error"] ?: "La materia no existe"
                        isLoading = false
                    }

                    HttpStatusCode.Forbidden -> {
                        val errorResponse = response.body<Map<String, String>>()
                        errorMessage = errorResponse["error"] ?: "No autorizado"
                        isLoading = false
                    }

                    HttpStatusCode.InternalServerError -> {
                        errorMessage = "Error interno del servidor"
                        isLoading = false
                    }

                    else -> {
                        errorMessage = "Error desconocido: ${response.status}"
                        isLoading = false
                    }
                }
            } catch (e: Exception) {
                errorMessage = "Error de conexión: ${e.localizedMessage}"
                isLoading = false
            }
        }
    }

    private fun descargarQR() {
        if (qrGenerated == null) {
            Toast.makeText(this, "No hay QR para descargar", Toast.LENGTH_SHORT).show()
            return
        }

        // Solo verificar permisos en Android 9 y anteriores
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.Q) {
            if (!PermissionManager.hasStoragePermission(this)) {
                PermissionManager.requestStoragePermission(this)
                return
            }
        }

        isDownloading = true

        try {
            // Convertir base64 a bitmap
            val base64String = qrGenerated!!.qr.qr_image.substringAfter("base64,")
            val decodedBytes = Base64.decode(base64String, Base64.DEFAULT)
            val bitmap = BitmapFactory.decodeByteArray(decodedBytes, 0, decodedBytes.size)

            // Guardar imagen en la galería
            saveImageToGallery(bitmap)

        } catch (e: Exception) {
            Toast.makeText(
                this,
                "Error al procesar la imagen: ${e.localizedMessage}",
                Toast.LENGTH_LONG
            ).show()
            isDownloading = false
        }
    }

    private fun saveImageToGallery(bitmap: Bitmap) {
        try {
            val materia = qrGenerated?.qr?.materia
            val timestamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.getDefault()).format(Date())
            val filename = "QR_INSCRIPCION_${materia?.codigo}_$timestamp.png"

            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                // Android 10+ (API 29+) - Usar MediaStore
                val contentValues = ContentValues().apply {
                    put(MediaStore.Images.Media.DISPLAY_NAME, filename)
                    put(MediaStore.Images.Media.MIME_TYPE, "image/png")
                    put(
                        MediaStore.Images.Media.RELATIVE_PATH,
                        Environment.DIRECTORY_PICTURES + "/QR_Inscripcion"
                    )
                }

                val uri = contentResolver.insert(
                    MediaStore.Images.Media.EXTERNAL_CONTENT_URI,
                    contentValues
                )

                uri?.let {
                    contentResolver.openOutputStream(it)?.use { outputStream ->
                        bitmap.compress(Bitmap.CompressFormat.PNG, 100, outputStream)
                    }

                    Toast.makeText(
                        this,
                        "QR guardado en la galería: $filename",
                        Toast.LENGTH_LONG
                    ).show()
                } ?: run {
                    Toast.makeText(this, "Error al crear el archivo", Toast.LENGTH_SHORT).show()
                }
            } else {
                // Android 9 y anteriores - Usar ruta directa
                val picturesDir =
                    Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_PICTURES)
                val qrDir = java.io.File(picturesDir, "QR_Inscripcion")

                if (!qrDir.exists()) {
                    qrDir.mkdirs()
                }

                val imageFile = java.io.File(qrDir, filename)

                imageFile.outputStream().use { outputStream ->
                    bitmap.compress(Bitmap.CompressFormat.PNG, 100, outputStream)
                }

                // Notificar al sistema que se agregó un archivo
                val contentValues = ContentValues().apply {
                    put(MediaStore.Images.Media.DATA, imageFile.absolutePath)
                    put(MediaStore.Images.Media.MIME_TYPE, "image/png")
                }
                contentResolver.insert(MediaStore.Images.Media.EXTERNAL_CONTENT_URI, contentValues)

                Toast.makeText(
                    this,
                    "QR guardado en: Pictures/QR_Inscripcion/$filename",
                    Toast.LENGTH_LONG
                ).show()
            }

            isDownloading = false

        } catch (e: IOException) {
            Toast.makeText(
                this,
                "Error al guardar la imagen: ${e.localizedMessage}",
                Toast.LENGTH_LONG
            ).show()
            isDownloading = false
        }
    }

    override fun onRequestPermissionsResult(
        requestCode: Int,
        permissions: Array<out String>,
        grantResults: IntArray
    ) {
        super.onRequestPermissionsResult(requestCode, permissions, grantResults)

        PermissionManager.handlePermissionResult(
            requestCode = requestCode,
            permissions = permissions,
            grantResults = grantResults,
            onStorageGranted = {
                Toast.makeText(this, "Permisos concedidos", Toast.LENGTH_SHORT).show()
                descargarQR() // Reintentar descarga
            },
            onStorageDenied = {
                Toast.makeText(
                    this,
                    "Se necesitan permisos de almacenamiento para descargar el QR",
                    Toast.LENGTH_LONG
                ).show()
            }
        )
    }

    private suspend fun getUserId(): String? {
        return dataStore.data.first()[USER_ID_KEY]
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun GenerarQRInscripcionScreen(
    qrGenerated: QRInscripcionResponse? = null,
    isLoading: Boolean = false,
    isDownloading: Boolean = false,
    errorMessage: String = "",
    onNavigateBack: () -> Unit = {},
    onGenerarQR: () -> Unit = {},
    onDescargarQR: () -> Unit = {}
) {
    val scrollState = rememberScrollState()

    Scaffold(
        topBar = {
            Column {
                TopAppBar(
                    title = {
                        Text(
                            text = "QR de Inscripción",
                            fontSize = 18.sp,
                            fontWeight = FontWeight.Bold,
                            modifier = Modifier.fillMaxWidth(),
                            textAlign = TextAlign.Center,
                            color = Color.White
                        )
                    },
                    navigationIcon = {
                        IconButton(onClick = onNavigateBack) {
                            Icon(
                                imageVector = Icons.Default.ArrowBack,
                                contentDescription = "Volver",
                                tint = Color.White
                            )
                        }
                    },
                    actions = {
                        if (qrGenerated != null) {
                            IconButton(onClick = onGenerarQR) {
                                Icon(
                                    imageVector = Icons.Default.Refresh,
                                    contentDescription = "Regenerar QR",
                                    tint = Color.White
                                )
                            }
                        }
                    },
                    colors = TopAppBarDefaults.topAppBarColors(
                        containerColor = Color(0xFF1E3A8A)
                    )
                )

                // Línea divisoria
                Divider(
                    thickness = 1.dp,
                    color = Color.White.copy(alpha = 0.3f)
                )
            }
        }
    ) { paddingValues ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(paddingValues)
                .verticalScroll(scrollState)
        ) {
            // Sección azul - Información de la materia
            qrGenerated?.let { qr ->
                Column(
                    modifier = Modifier
                        .fillMaxWidth()
                        .background(Color(0xFF1E3A8A))
                        .padding(16.dp),
                    verticalArrangement = Arrangement.spacedBy(16.dp)
                ) {
                    InformacionMateriaInscripcion(
                        nombre = qr.qr.materia.nombre,
                        codigo = qr.qr.materia.codigo,
                        grupo = qr.qr.materia.grupo
                    )
                }
            }

            // Sección blanca - QR y controles
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .background(Color.White)
                    .padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(16.dp)
            ) {
                when {
                    isLoading -> {
                        // Estado de carga
                        QRInscripcionLoadingSection()
                    }

                    errorMessage.isNotEmpty() -> {
                        // Estado de error
                        QRInscripcionErrorSection(
                            errorMessage = errorMessage,
                            onRetry = onGenerarQR
                        )
                    }

                    qrGenerated != null -> {
                        // QR generado exitosamente
                        QRInscripcionSuccessSection(
                            qrData = qrGenerated,
                            isDownloading = isDownloading,
                            onDescargar = onDescargarQR
                        )
                    }
                }
            }
        }
    }
}

